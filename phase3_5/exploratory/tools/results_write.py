def check(d: str) -> int:
    """0 if RESULTS.md equals its regeneration, else 1 with the first differing line printed."""
    expected = render(d)
    actual = io.open(os.path.join(d, "RESULTS.md"), encoding="utf-8").read()
    if expected == actual:
        return 0
    e, a = expected.split("\n"), actual.split("\n")
    for i, (x, y) in enumerate(zip(e, a), 1):
        if x != y:
            print("RESULTS.md differs from its regeneration at line %d:\n  file: %s\n  tables: %s" % (i, y[:110], x[:110]))
            break
    else:
        print("RESULTS.md differs from its regeneration in length (%d vs %d lines)" % (len(a), len(e)))
    return 1


